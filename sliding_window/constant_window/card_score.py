class Solution:
    def max_score(self, card_score,k):
        n = len(card_score)
        total_sum = sum(card_score)
        # window of size n-k (inclusive)
        size = n-k
        # initialize from left
        i = 0
        j = i+size
        curr_sum = sum(card_score[i:j])
        min_sum = curr_sum
        while j<n:
            # expand & shrink
            curr_sum += (card_score[j] - card_score[i])
            j += 1
            i += 1
            min_sum = min(min_sum,curr_sum)

        return total_sum - min_sum



        
                

